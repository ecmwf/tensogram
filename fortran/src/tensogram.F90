   !> Fetch one non-finite bitmask kind for a mask-aware decoded object into
   !> `mask`: a flat rank-1 int8 array with ONE BYTE PER ELEMENT in row-major
   !> (on-wire, descriptor-shape) element order — 1 where the element held the
   !> requested `kind` (TGM_MASK_KIND_NAN / _POS_INF / _NEG_INF) at encode time,
   !> 0 otherwise. size(mask) equals the element count (the shape product).
   !> A size-0 `mask` means that kind is ABSENT (the object carried no mask of
   !> that kind, or the handle was not produced by tensogram_decode_with_masks).
   !> `err` is TGM_ERROR_OK for a valid fetch (present OR genuinely absent) and
   !> TGM_ERROR_INVALID_ARG for an unknown `kind` or an out-of-range `iobj`
   !> (in which case `mask` is size 0). NOTE: the bytes stay in the C row-major
   !> order — for a multi-dimensional object this is the transpose of the
   !> Fortran element order (see the memory-order contract); for rank ≤ 1 the
   !> two orders coincide.
   subroutine tensogram_object_mask(msg, iobj, kind, mask, err)
      type(tensogram_message),        intent(in)  :: msg
      integer,                        intent(in)  :: iobj
      integer(c_int),                 intent(in)  :: kind
      integer(c_int8_t), allocatable, intent(out) :: mask(:)
      integer(c_int),                 intent(out) :: err
      type(tgm_bytes_t)          :: raw
      integer(c_int8_t), pointer :: view(:)
      err = TGM_ERROR_OK
      if (kind /= TGM_MASK_KIND_NAN .and. kind /= TGM_MASK_KIND_POS_INF .and. &
          kind /= TGM_MASK_KIND_NEG_INF) then
         err = TGM_ERROR_INVALID_ARG          ! unknown mask kind
         allocate(mask(0))
         return
      end if
      if (iobj < 1 .or. iobj > tensogram_num_objects(msg)) then
         err = TGM_ERROR_INVALID_ARG          ! out-of-range object (or null handle)
         allocate(mask(0))
         return
      end if
      raw = c_tgm_object_mask(msg%ptr, int(iobj - 1, c_size_t), kind)
      allocate(mask(raw%len))                 ! size 0 => that kind is absent
      if (raw%len > 0_c_size_t .and. c_associated(raw%data)) then
         call c_f_pointer(raw%data, view, [raw%len])
         mask = view
      end if
      call c_tgm_bytes_free(raw)
   end subroutine tensogram_object_mask

