   !> Scan a buffer for message boundaries. For each message found, `offsets(k)`
   !> is its 1-BASED start index into `buffer` and `lengths(k)` is its byte
   !> length, so message k is `buffer(offsets(k) : offsets(k) + lengths(k) - 1)`.
   !> Both arrays are allocated to the message count (size 0 on error / empty
   !> buffer).
   subroutine tensogram_scan(buffer, offsets, lengths, err)
      integer(c_int8_t), target, contiguous, intent(in)  :: buffer(:)
      integer(c_size_t), allocatable,        intent(out) :: offsets(:)
      integer(c_size_t), allocatable,        intent(out) :: lengths(:)
      integer(c_int),                        intent(out) :: err
      type(c_ptr) :: res
      err = c_tgm_scan(buf_ptr(buffer), size(buffer, kind=c_size_t), res)
      call collect_scan(err, res, offsets, lengths)
   end subroutine tensogram_scan

   !> Shared result-collection for the scan family: on a non-OK `err` allocate
   !> empty outputs; otherwise drain the tgm_scan_result_t handle `res` into
   !> `offsets` (1-based Fortran start index into the buffer) and `lengths`
   !> (byte length), then free the handle. Message k is
   !> `buffer(offsets(k) : offsets(k) + lengths(k) - 1)`.
   subroutine collect_scan(err, res, offsets, lengths)
      integer(c_int),                 intent(in)  :: err
      type(c_ptr),                    intent(in)  :: res
      integer(c_size_t), allocatable, intent(out) :: offsets(:)
      integer(c_size_t), allocatable, intent(out) :: lengths(:)
      type(tgm_scan_entry_t) :: entry
      integer(c_size_t)      :: n, k
      if (err /= TGM_ERROR_OK) then
         allocate(offsets(0), lengths(0))
         return
      end if
      n = c_tgm_scan_count(res)
      allocate(offsets(n), lengths(n))
      do k = 1_c_size_t, n
         entry = c_tgm_scan_entry(res, k - 1_c_size_t)
         offsets(k) = entry%offset + 1_c_size_t  ! 1-based Fortran index into buffer
         lengths(k) = entry%length
      end do
      call c_tgm_scan_free(res)
   end subroutine collect_scan

   !> Scan a `.tgm` file for message boundaries using streaming seek-and-read
   !> I/O (the whole file is never loaded into memory). `offsets` / `lengths`
   !> follow the tensogram_scan contract, but index into the FILE (1-based byte
   !> offset). Size 0 on error. `err` is TGM_ERROR_IO if the file cannot be
   !> opened / seeked / read, TGM_ERROR_INVALID_ARG for a non-UTF-8 path.
   subroutine tensogram_scan_file(path, offsets, lengths, err)
      character(len=*),               intent(in)  :: path
      integer(c_size_t), allocatable, intent(out) :: offsets(:)
      integer(c_size_t), allocatable, intent(out) :: lengths(:)
      integer(c_int),                 intent(out) :: err
      character(kind=c_char), allocatable, target :: path_c(:)
      type(c_ptr) :: res
      call f_to_cstr(trim(path), path_c)
      err = c_tgm_scan_file(c_loc(path_c), res)
      call collect_scan(err, res, offsets, lengths)
   end subroutine tensogram_scan_file

   !> Resolve an optional tensogram_scan_options to a C pointer. `opts_c` is a
   !> caller-owned target copy that must outlive the C call; when `opts` is
   !> absent the pointer is NULL (library defaults: bidirectional, 4 GiB cap).
   subroutine resolve_scan_opts(opts, opts_c, opts_ptr)
      type(tensogram_scan_options), intent(in), optional :: opts
