   type :: tensogram_value
      type(c_ptr), private :: ptr = c_null_ptr
   contains
      procedure :: is_present => value_is_present  !> non-NULL handle?
      procedure :: kind       => value_kind        !> TGM_VALUE_TYPE_* code
