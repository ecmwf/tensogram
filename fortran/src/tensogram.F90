   subroutine f_to_cstr(f, c)
      character(len=*),                    intent(in)  :: f
      character(kind=c_char), allocatable, intent(out) :: c(:)
      integer :: i, n
      n = len(f)
      allocate(c(n + 1))
      do i = 1, n
         c(i) = f(i:i)
      end do
      c(n + 1) = c_null_char
   end subroutine f_to_cstr

   function cptr_to_fstr(p) result(f)
      type(c_ptr), intent(in)         :: p
      character(len=:), allocatable   :: f
      character(kind=c_char), pointer :: buf(:)
      integer(c_size_t) :: n
      integer :: i
      if (.not. c_associated(p)) then
         f = ''
         return
      end if
      n = c_strlen(p)
      call c_f_pointer(p, buf, [n])
      allocate(character(len=int(n)) :: f)
      do i = 1, int(n)
         f(i:i) = buf(i)
      end do
   end function cptr_to_fstr

   !> Copy exactly `n` bytes from a borrowed C buffer into a Fortran string.
   !> Unlike cptr_to_fstr this does NOT stop at (nor require) a terminating
   !> NUL: the metadata value cursor lends UTF-8 `ptr + len` buffers that may
   !> hold interior NUL bytes and are not NUL-terminated. A zero length yields
   !> an empty string WITHOUT dereferencing `p` (safe for the empty-string /
   !> empty-key case, where `p` may be a non-dereferenceable sentinel).
   function cptr_len_to_fstr(p, n) result(f)
      type(c_ptr),       intent(in) :: p
      integer(c_size_t), intent(in) :: n
      character(len=:), allocatable   :: f
      character(kind=c_char), pointer :: buf(:)
      integer :: i
      allocate(character(len=int(n)) :: f)
      if (n == 0_c_size_t) return
      call c_f_pointer(p, buf, [n])
      do i = 1, int(n)
         f(i:i) = buf(i)
      end do
   end function cptr_len_to_fstr

   !> C-address of a contiguous int8 buffer, or C_NULL_PTR for a zero-size
   !> buffer. Honours the C ABI's "buf may be NULL when buf_len == 0" contract
   !> (validate / scan / decode*) and avoids taking c_loc of a zero-size array.
   function buf_ptr(b) result(p)
      integer(c_int8_t), target, contiguous, intent(in) :: b(:)
      type(c_ptr) :: p
      if (size(b) > 0) then
         p = c_loc(b)
      else
         p = c_null_ptr
      end if
   end function buf_ptr

   !> Copy a Rust-owned tgm_bytes_t (UTF-8, length-delimited, NOT
   !> NUL-terminated) into an allocatable Fortran string, then release it with
   !> tgm_bytes_free. Shared by the JSON-report (doctor / validate) and
   !> hex-digest (compute_hash) wrappers — the ptr+len payloads carry no
   !> terminating NUL, so cptr_len_to_fstr (exact len, no strlen) is used,
   !> mirroring the C++ `std::string(data, len)` + `tgm_bytes_free` idiom.
   function take_bytes_str(raw) result(s)
      type(tgm_bytes_t), intent(in) :: raw
      character(len=:), allocatable :: s
      s = cptr_len_to_fstr(raw%data, raw%len)
      call c_tgm_bytes_free(raw)
   end function take_bytes_str

   pure function itoa(i) result(s)
      integer(c_int64_t), intent(in) :: i
      character(len=:), allocatable  :: s
      character(len=32)              :: tmp
      write (tmp, '(i0)') i
      s = trim(tmp)
   end function itoa

   !> Comma-separated list of int64 values ('' for an empty vector).
   pure function i64list(v) result(s)
      integer(c_int64_t), intent(in) :: v(:)
      character(len=:), allocatable  :: s
      integer :: k
      s = ''
      do k = 1, size(v)
         if (k > 1) s = s // ','
         s = s // itoa(v(k))
      end do
   end function i64list

   pure function host_byte_order() result(bo)
      character(len=:), allocatable :: bo
      integer(c_int8_t) :: bytes(4)
      bytes = transfer(1_c_int32_t, 0_c_int8_t, 4)
      if (bytes(1) == 1_c_int8_t) then
         bo = 'little'
      else
         bo = 'big'
      end if
   end function host_byte_order

   !> Resolve the optional hash-algorithm name to a C string pointer. Fills
   !> `hash_c` (a caller-owned target buffer that must outlive the C call) and
   !> `hash_ptr`: a present-but-empty name means "no hash" (NULL); absent means
   !> the default "xxh3".
   subroutine resolve_hash(hash, hash_c, hash_ptr)
      character(len=*), intent(in), optional :: hash
      character(kind=c_char), allocatable, target, intent(out) :: hash_c(:)
      type(c_ptr),                                 intent(out) :: hash_ptr
      character(len=:), allocatable :: hash_s
      if (present(hash)) then
         hash_s = trim(hash)            ! drop fixed-length padding
      else
         hash_s = 'xxh3'
      end if
      if (len(hash_s) == 0) then
         hash_ptr = c_null_ptr
      else
         call f_to_cstr(hash_s, hash_c)
         hash_ptr = c_loc(hash_c)
      end if
   end subroutine resolve_hash

   !> Marshal a Fortran string array into the C `const char *const *` shape:
   !> `flat` is ONE contiguous buffer holding every trimmed string with its
   !> NUL terminator, and `ptrs(k)` points at entry k inside it. Both are
   !> caller-owned targets that must outlive the C call (the resolve_hash
   !> pattern). Trailing blanks — unavoidable in a fixed-length array literal
   !> — are dropped, as everywhere else in this binding. A zero-size `strs`
   !> still allocates size-1 dummies so nothing ever takes c_loc of a
   !> zero-size array; pass NULL alongside n_options = 0 in that case.
   subroutine cstr_array(strs, flat, ptrs)
      character(len=*),                            intent(in)  :: strs(:)
      character(kind=c_char), allocatable, target, intent(out) :: flat(:)
      type(c_ptr),            allocatable,         intent(out) :: ptrs(:)
      integer :: n, k, i, total, pos, ln
      n = size(strs)
      total = 0
      do k = 1, n
         total = total + len_trim(strs(k)) + 1
      end do
      allocate(flat(max(total, 1)), ptrs(max(n, 1)))
      flat = c_null_char
      ptrs = c_null_ptr
      pos = 1
      do k = 1, n
         ln = len_trim(strs(k))
         do i = 1, ln
            flat(pos + i - 1) = strs(k)(i:i)
         end do
         flat(pos + ln) = c_null_char
         ptrs(k) = c_loc(flat(pos))
         pos = pos + ln + 1
      end do
   end subroutine cstr_array

   !> Resolve an optional mask-method name to a C string pointer. `name_c` is
   !> a caller-owned target buffer that must outlive the C call; an absent (or
   !> empty) name is NULL, which selects the library default ("roaring").
   subroutine resolve_method(name, name_c, name_ptr)
      character(len=*), intent(in), optional :: name
      character(kind=c_char), allocatable, target, intent(out) :: name_c(:)
      type(c_ptr),                                 intent(out) :: name_ptr
      name_ptr = c_null_ptr
      if (.not. present(name)) return
      if (len_trim(name) == 0) return
      call f_to_cstr(trim(name), name_c)
      name_ptr = c_loc(name_c)
   end subroutine resolve_method

   !> Fill a TgmEncodeOptions POD from the optional arguments the
   !> tensogram_*_with_options wrappers share. Every field starts at the
   !> library default (see the POD), so only what the caller asked for is
   !> touched. The four `*_c` buffers hold the C strings the POD points at and
   !> must outlive the C call — they are the caller's targets, exactly as in
   !> resolve_hash. `hash` follows the Fortran binding's convention (absent =>
   !> "xxh3", '' => no hashing), NOT the C ABI's NULL-means-no-hashing.
   subroutine resolve_encode_opts(opts, hash_c, nan_c, pos_c, neg_c, hash,     &
                                  aggregate_hash, compression_backend,         &
                                  allow_nan, allow_inf, nan_mask_method,       &
                                  pos_inf_mask_method, neg_inf_mask_method,    &
                                  small_mask_threshold_bytes)
      type(tgm_encode_options_t), intent(out) :: opts
      character(kind=c_char), allocatable, target, intent(out) :: hash_c(:)
      character(kind=c_char), allocatable, target, intent(out) :: nan_c(:)
      character(kind=c_char), allocatable, target, intent(out) :: pos_c(:)
      character(kind=c_char), allocatable, target, intent(out) :: neg_c(:)
      character(len=*),   intent(in), optional :: hash
      integer(c_int),     intent(in), optional :: aggregate_hash
      integer(c_int),     intent(in), optional :: compression_backend
      logical,            intent(in), optional :: allow_nan, allow_inf
      character(len=*),   intent(in), optional :: nan_mask_method
      character(len=*),   intent(in), optional :: pos_inf_mask_method
      character(len=*),   intent(in), optional :: neg_inf_mask_method
      integer(c_int64_t), intent(in), optional :: small_mask_threshold_bytes
      call resolve_hash(hash, hash_c, opts%hash)
      if (present(aggregate_hash))      opts%aggregate_hash      = aggregate_hash
      if (present(compression_backend)) opts%compression_backend = compression_backend
      if (present(allow_nan)) opts%allow_nan = logical(allow_nan, kind=c_bool)
      if (present(allow_inf)) opts%allow_inf = logical(allow_inf, kind=c_bool)
      call resolve_method(nan_mask_method,     nan_c, opts%nan_mask_method)
      call resolve_method(pos_inf_mask_method, pos_c, opts%pos_inf_mask_method)
      call resolve_method(neg_inf_mask_method, neg_c, opts%neg_inf_mask_method)
      if (present(small_mask_threshold_bytes)) &
         opts%small_mask_threshold_bytes = small_mask_threshold_bytes
   end subroutine resolve_encode_opts

   !> Marshal concatenated per-object bytes into the C parallel arrays: object
   !> k is data(off+1 : off+lens(k)), so num_objects = size(lens) and
   !> sum(lens) == size(data). `ptrs` / `lens_c` are caller-owned targets that
   !> must outlive the C call; `ptrs_ptr` / `lens_ptr` are NULL for the
   !> zero-object case (never take c_loc of a zero-size array).
   subroutine object_arrays(data, lens, ptrs, lens_c, ptrs_ptr, lens_ptr)
      integer(c_int8_t), target, contiguous,  intent(in)  :: data(:)
      integer(c_size_t),                      intent(in)  :: lens(:)
      type(c_ptr),       allocatable, target, intent(out) :: ptrs(:)
      integer(c_size_t), allocatable, target, intent(out) :: lens_c(:)
      type(c_ptr),                            intent(out) :: ptrs_ptr, lens_ptr
      integer(c_size_t) :: off
      integer :: nobj, k
      nobj = size(lens)
      allocate(ptrs(max(nobj, 1)), lens_c(max(nobj, 1)))
      ptrs   = c_null_ptr
      lens_c = 0_c_size_t
      off = 0_c_size_t
      do k = 1, nobj
         if (lens(k) > 0_c_size_t) ptrs(k) = c_loc(data(off + 1_c_size_t))
         lens_c(k) = lens(k)
         off = off + lens(k)
      end do
      if (nobj > 0) then
         ptrs_ptr = c_loc(ptrs)
         lens_ptr = c_loc(lens_c)
      else
         ptrs_ptr = c_null_ptr
         lens_ptr = c_null_ptr
      end if
   end subroutine object_arrays

   !> Total element count for a Fortran extent vector (1 for a scalar / empty).
   pure function num_elements(ext) result(n)
      integer(c_int64_t), intent(in) :: ext(:)
      integer(c_size_t) :: n
      n = product([1_c_size_t, int(ext, c_size_t)])
   end function num_elements

   !> Wire payload byte count = element count × element byte width (`bits/8`).
   !> Deriving the width from `storage_size(a)` keeps it consistent with the
   !> actual Fortran type rather than a hard-coded literal per dtype wrapper.
   pure function byte_count(num, bits) result(n)
      integer(c_size_t), intent(in) :: num, bits
      integer(c_size_t) :: n
      n = num * (bits / 8_c_size_t)
   end function byte_count

   !> Build the one-object descriptor JSON. `fshape` is the Fortran
   !> (column-major) extents; the on-wire shape and C-contiguous strides are
   !> the REVERSE (see the memory-order contract above). `extra`, if present, is raw JSON of
   !> additional top-level keys appended verbatim.
   !> Build a single DataObjectDescriptor object `{...}` with the on-wire
   !> shape and C-contiguous strides REVERSED from the Fortran extents
   !> (column-major contract). Used directly by the streaming encoder; wrapped
   !> in `{"descriptors":[...]}` by descriptor_json for the buffer/file path.
   function descriptor_object_json(fshape, dtype, encoding, filter, compression) result(js)
      integer(c_int64_t), intent(in)           :: fshape(:)
      character(len=*),   intent(in)           :: dtype
      character(len=*),   intent(in), optional :: encoding, filter, compression
      character(len=:), allocatable :: js, enc_s, flt_s, cmp_s
      integer(c_int64_t), allocatable :: wshape(:), wstrides(:)
      integer :: nd, k
      nd = size(fshape)
      allocate(wshape(nd), wstrides(nd))
      do k = 1, nd
         wshape(k) = fshape(nd - k + 1)          ! reverse to C order
      end do
      if (nd > 0) then
         wstrides(nd) = 1_c_int64_t
         do k = nd - 1, 1, -1
            wstrides(k) = wstrides(k + 1) * wshape(k + 1)
         end do
      end if
      enc_s = 'none'; if (present(encoding))    enc_s = trim(encoding)
      flt_s = 'none'; if (present(filter))      flt_s = trim(filter)
      cmp_s = 'none'; if (present(compression)) cmp_s = trim(compression)
      js = '{"type":"ntensor","ndim":' // itoa(int(nd, c_int64_t)) // &
           ',"shape":['   // i64list(wshape)   // ']' //                   &
           ',"strides":[' // i64list(wstrides) // ']' //                   &
           ',"dtype":"' // trim(dtype) // '","byte_order":"' // host_byte_order() // '"' // &
           ',"encoding":"' // enc_s // '","filter":"' // flt_s // &
           '","compression":"' // cmp_s // '"}'
   end function descriptor_object_json

   !> Wrap one descriptor in the `{"descriptors":[...], <extra>}` envelope the
   !> buffer/file encode entry points expect. `extra` is raw top-level JSON.
   function descriptor_json(fshape, dtype, extra, encoding, filter, compression) result(js)
      integer(c_int64_t), intent(in)           :: fshape(:)
      character(len=*),   intent(in)           :: dtype
      character(len=*),   intent(in), optional :: extra
      character(len=*),   intent(in), optional :: encoding, filter, compression
      character(len=:), allocatable :: js, e
      js = '{"descriptors":[' // &
           descriptor_object_json(fshape, dtype, encoding, filter, compression) // ']'
      if (present(extra)) then
         ! `extra` may be a complete JSON object (`{ ... }`, matching the
         ! streaming metadata argument) or a raw top-level key fragment
         ! (`"base":[...]`, e.g. the output of tensogram_meta%base_json()).
         ! Strip the outer braces of a complete object so the result is a
         ! single valid object either way.
         e = trim(adjustl(extra))
         if (len(e) >= 2) then
            if (e(1:1) == '{' .and. e(len(e):len(e)) == '}') e = e(2:len(e) - 1)
         end if
         if (len_trim(e) > 0) js = js // ',' // e
      end if
      js = js // '}'
   end function descriptor_json

